import os
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

from typer.testing import CliRunner

from cli import app


class InstructionsTest(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.config = self.root / "instructions" / "agents"
        self.config.mkdir(parents=True)
        (self.root / "out").mkdir()
        self.template = self.root / "instructions" / "template.md"
        self.template.write_text("# 公共\n\n{{ github.tools }}\n\n{{ harness.instructions }}\n", encoding="utf-8")
        (self.config / "default.toml").write_text(
            '[github.tools]\nvalue = "默认工具"\n[harness.instructions]\nvalue = ""\n', encoding="utf-8"
        )
        (self.config / "codex.toml").write_text(
            '[target]\noutput = "out/codex.md"\n[harness.instructions]\nvalue = "Codex 专属"\n', encoding="utf-8"
        )
        (self.config / "claude.toml").write_text('[target]\noutput = "out/claude.md"\n', encoding="utf-8")
        self.runner = CliRunner()

    def run_cli(self, *args):
        return self.runner.invoke(app, ["instructions", *args, "--root", str(self.root)])

    def test_selected_target_order_default_and_repeat(self):
        result = self.run_cli("sync", "codex")
        self.assertEqual(result.exit_code, 0, result.output)
        target = self.root / "out" / "codex.md"
        text = target.read_text(encoding="utf-8")
        self.assertTrue(text.startswith("# 公共"))
        self.assertNotIn("Generated by agentctl", text)
        self.assertLess(text.index("# 公共"), text.index("默认工具"))
        self.assertLess(text.index("默认工具"), text.index("Codex 专属"))
        self.assertFalse((self.root / "out" / "claude.md").exists())
        before = target.stat().st_mtime_ns
        self.assertEqual(self.run_cli("sync", "codex").exit_code, 0)
        self.assertEqual(target.stat().st_mtime_ns, before)

    def test_generated_state_protects_manual_edits(self):
        self.assertEqual(self.run_cli("sync", "codex").exit_code, 0)
        target = self.root / "out" / "codex.md"
        target.write_text("人工修改", encoding="utf-8")
        result = self.run_cli("sync", "codex")
        self.assertEqual(result.exit_code, 2)
        self.assertEqual(target.read_text(), "人工修改")
        self.assertEqual(self.run_cli("sync", "codex", "--force").exit_code, 0)
        self.template.write_text(self.template.read_text() + "新规则\n", encoding="utf-8")
        self.assertEqual(self.run_cli("sync", "codex").exit_code, 0)
        self.assertIn("新规则", target.read_text())

    def test_dry_run_and_check(self):
        result = self.run_cli("sync", "--dry-run")
        self.assertEqual(result.exit_code, 0, result.output)
        self.assertIn("+默认工具", result.output)
        self.assertEqual(list((self.root / "out").iterdir()), [])
        self.assertEqual(self.run_cli("check").exit_code, 1)
        self.assertEqual(self.run_cli("sync").exit_code, 0)
        self.assertEqual(self.run_cli("check").exit_code, 0)
        self.template.write_text(self.template.read_text() + "变更\n", encoding="utf-8")
        self.assertEqual(self.run_cli("check").exit_code, 1)

    def test_missing_and_unused_keys(self):
        self.template.write_text(self.template.read_text() + "{{ new.key }}\n", encoding="utf-8")
        result = self.run_cli("sync")
        self.assertEqual(result.exit_code, 2)
        self.assertIn("new", result.output)
        self.assertEqual(list((self.root / "out").iterdir()), [])
        self.template.write_text("{{ github.tools }}\n", encoding="utf-8")
        result = self.run_cli("check")
        self.assertEqual(result.exit_code, 2)
        self.assertIn("未使用", result.output)

    def test_missing_template_and_unknown_target(self):
        self.template.unlink()
        self.assertEqual(self.run_cli("sync").exit_code, 2)
        self.template.write_text("{{ github.tools }}", encoding="utf-8")
        self.assertIn("未知 target", self.run_cli("sync", "unknown").output)

    def test_literal_placeholder_keys_and_plain_text(self):
        self.template.write_bytes(
            b"{{ github[field] }}\r\n{{ github.tools | upper }}\r\n{% if x %}\r\n{{ unfinished\r\n"
        )
        (self.config / "default.toml").write_text(
            '["github[field]"]\nvalue = "first"\n["github.tools | upper"]\nvalue = "second"\n', encoding="utf-8"
        )
        (self.config / "codex.toml").write_text('[target]\noutput = "out/codex.md"\n', encoding="utf-8")
        result = self.run_cli("sync", "codex")
        self.assertEqual(result.exit_code, 0, result.output)
        self.assertEqual(
            (self.root / "out" / "codex.md").read_bytes(),
            b"first\r\nsecond\r\n{% if x %}\r\n{{ unfinished\r\n",
        )

    def test_empty_placeholder_and_config_key_collision(self):
        self.template.write_text("{{   }}", encoding="utf-8")
        self.assertIn("空 key", self.run_cli("sync", "codex").output)
        self.template.write_text("{{ github.tools }}", encoding="utf-8")
        (self.config / "default.toml").write_text(
            '[github.tools]\nvalue = "a"\n["github.tools"]\nvalue = "b"\n', encoding="utf-8"
        )
        result = self.run_cli("sync", "codex")
        self.assertEqual(result.exit_code, 2)
        self.assertIn("配置 key 冲突: github.tools", result.output)

    def test_handwritten_file_preflight_and_force(self):
        target = self.root / "out" / "codex.md"
        target.write_text("手写", encoding="utf-8")
        result = self.run_cli("sync")
        self.assertEqual(result.exit_code, 2)
        self.assertFalse((self.root / "out" / "claude.md").exists())
        self.assertEqual(target.read_text(), "手写")
        self.assertEqual(self.run_cli("sync", "codex", "--force").exit_code, 0)
        self.assertIn("Codex 专属", target.read_text())

    def test_symlink_force_replaces_link_only(self):
        original = self.root / "source.md"
        original.write_text("原始内容", encoding="utf-8")
        target = self.root / "out" / "codex.md"
        try:
            target.symlink_to(original)
        except OSError as exc:
            self.skipTest(f"当前系统不支持创建软链接: {exc}")
        self.assertEqual(self.run_cli("sync", "codex").exit_code, 2)
        self.assertEqual(self.run_cli("sync", "codex", "--force").exit_code, 0)
        self.assertFalse(target.is_symlink())
        self.assertEqual(original.read_text(), "原始内容")

    def test_duplicate_paths_and_missing_directory(self):
        (self.config / "claude.toml").write_text('[target]\noutput = "out/codex.md"\n', encoding="utf-8")
        self.assertIn("冲突", self.run_cli("sync").output)
        (self.config / "claude.toml").write_text('[target]\noutput = "missing/file.md"\n', encoding="utf-8")
        self.assertIn("目录不存在", self.run_cli("sync").output)

    def test_write_failure_reports_partial_success(self):
        from commands import instructions

        actual = instructions.write
        def fail_second(item, force):
            if item.name == "codex":
                raise instructions.InstructionError("模拟写入失败")
            return actual(item, force)

        with patch.object(instructions, "write", side_effect=fail_second):
            result = self.run_cli("sync")
        self.assertEqual(result.exit_code, 2)
        self.assertIn("已更新: claude", result.output)
        self.assertTrue((self.root / "out" / "claude.md").exists())
        self.assertFalse((self.root / "out" / "codex.md").exists())

    def test_existing_lock_prevents_write(self):
        lock = self.root / "out" / ".codex.md.agentctl.lock"
        lock.write_text("other process", encoding="utf-8")
        self.assertEqual(self.run_cli("sync", "codex").exit_code, 2)
        self.assertTrue(lock.exists())

    def test_test_output_uses_target_config_and_never_falls_back(self):
        test_dir = self.root / "test-output"
        test_dir.mkdir()
        config = self.config / "codex.toml"
        config.write_text(config.read_text().replace('output = "out/codex.md"', 'output = "out/codex.md"\ntest_output = "test-output/codex.md"'), encoding="utf-8")
        result = self.run_cli("sync", "codex", "--test")
        self.assertEqual(result.exit_code, 0, result.output)
        self.assertTrue((test_dir / "codex.md").exists())
        self.assertFalse((self.root / "out" / "codex.md").exists())
        self.assertEqual(self.run_cli("check", "codex", "--test").exit_code, 0)
        result = self.run_cli("sync", "--test")
        self.assertEqual(result.exit_code, 2)
        self.assertIn("缺少测试输出路径", result.output)
        self.assertFalse((self.root / "out" / "claude.md").exists())

    def test_test_output_parent_created_only_when_writing(self):
        config = self.config / "codex.toml"
        config.write_text(config.read_text().replace('output = "out/codex.md"', 'output = "out/codex.md"\ntest_output = "new/nested/codex.md"'), encoding="utf-8")
        self.assertEqual(self.run_cli("sync", "codex", "--test", "--dry-run").exit_code, 0)
        self.assertFalse((self.root / "new").exists())
        result = self.run_cli("sync", "codex", "--test")
        self.assertEqual(result.exit_code, 0, result.output)
        self.assertTrue((self.root / "new" / "nested" / "codex.md").exists())


if __name__ == "__main__":
    unittest.main()
