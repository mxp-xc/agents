from __future__ import annotations

import difflib
import os
import sys
import tempfile
import tomllib
from dataclasses import dataclass
from pathlib import Path
from typing import Annotated

import typer

from commands.instruction_template import TemplateError, flatten, render

app = typer.Typer(help="生成和检查各 harness 的指令文件。", no_args_is_help=True)
MARKER = "<!-- Generated by agentctl instructions; edit the sources listed below. -->"
class InstructionError(Exception):
    pass


def read(path: Path) -> str:
    try:
        return path.read_bytes().decode("utf-8")
    except (OSError, UnicodeError) as exc:
        raise InstructionError(f"读取失败 {path}: {exc}") from exc


def load(path: Path) -> dict:
    try:
        return tomllib.loads(read(path))
    except tomllib.TOMLDecodeError as exc:
        raise InstructionError(f"TOML 无效 {path}: {exc}") from exc


@dataclass
class Plan:
    name: str
    path: Path
    text: str
    previous: str | None
    symlink: bool


def state_path(path: Path) -> Path:
    return path.with_name(f".{path.name}.agentctl-state")


def is_generated(path: Path, previous: str | None) -> bool:
    if previous is None:
        return False
    if previous.startswith(MARKER + "\n"):
        return True
    state = state_path(path)
    if state.is_symlink() or not state.is_file():
        return False
    return read(state) == MARKER + "\n" + previous


def plan(root: Path, targets: list[str], force: bool, writing: bool, test: bool) -> list[Plan]:
    folder = root / "instructions"
    config_dir = folder / "agents"
    template_path = folder / "template.md"
    default_path = config_dir / "default.toml"
    template = read(template_path)
    try:
        defaults = flatten(load(default_path), default_path) if default_path.exists() else {}
    except TemplateError as exc:
        raise InstructionError(str(exc)) from exc
    configs = {p.stem: p for p in config_dir.glob("*.toml") if p.stem != "default"}
    if not configs:
        raise InstructionError(f"未找到 target 配置: {config_dir}")
    names = targets or sorted(configs)
    if len(names) != len(set(names)):
        raise InstructionError("target 重复")
    missing_names = set(names) - configs.keys()
    if missing_names:
        raise InstructionError(f"未知 target: {', '.join(sorted(missing_names))}")
    inputs = {template_path.resolve(), default_path.resolve()}
    inputs.update(p.resolve() for p in configs.values())
    paths = set()
    plans = []
    for name in names:
        config = configs[name]
        data = load(config)
        target = data.pop("target", None)
        if not isinstance(target, dict) or set(target) - {"output", "test_output"} or not isinstance(target.get("output"), str) or not target["output"]:
            raise InstructionError(f"{config}: [target] 必须包含非空字符串 output，且仅允许配置 output 和 test_output")
        if "test_output" in target and (not isinstance(target["test_output"], str) or not target["test_output"]):
            raise InstructionError(f"{config}: test_output 必须是非空字符串")
        if test and "test_output" not in target:
            raise InstructionError(f"{config}: 缺少测试输出路径 test_output")
        try:
            overrides = flatten(data, config)
            rendered = render(template, defaults, overrides)
        except TemplateError as exc:
            raise InstructionError(f"{name}: 模板渲染失败: {exc}") from exc
        raw_path = os.path.expandvars(os.path.expanduser(target["test_output"] if test else target["output"]))
        output = Path(os.path.abspath(root / raw_path))
        if not output.parent.is_dir() and (not test or output.parent.exists()):
            raise InstructionError(f"{name}: 目标目录不存在: {output.parent}")
        canonical = output.parent.resolve() / output.name
        state_canonical = canonical.with_name(f".{canonical.name}.agentctl-state")
        if canonical in paths or canonical in inputs or state_canonical in paths or state_canonical in inputs:
            raise InstructionError(f"{name}: 目标与源文件或其他目标冲突: {output}")
        paths.update((canonical, state_canonical))
        symlink = output.is_symlink()
        if output.exists() and not output.is_file() and not symlink:
            raise InstructionError(f"{name}: 目标不是普通文件: {output}")
        previous = read(output) if output.exists() and not symlink else None
        state = state_path(output)
        if writing and not force and (state.is_symlink() or (
            state.exists() and (not state.is_file() or not read(state).startswith(MARKER + "\n"))
        )):
            raise InstructionError(f"{name}: 拒绝覆盖已有记录文件: {state}；需要显式 --force")
        if writing and not force and (symlink or (previous is not None and previous != rendered and not is_generated(output, previous))):
            raise InstructionError(f"{name}: 拒绝覆盖手写文件或软链接: {output}；需要显式 --force")
        plans.append(Plan(name, output, rendered, previous, symlink))
    return plans


def write(item: Plan, force: bool) -> bool:
    lock = item.path.with_name(f".{item.path.name}.agentctl.lock")
    fd = None
    temporary = None
    replaced = False
    try:
        fd = os.open(lock, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
        symlink = item.path.is_symlink()
        previous = read(item.path) if item.path.exists() and not symlink else None
        if symlink != item.symlink or previous != item.previous:
            raise InstructionError(f"目标在预检后发生变化: {item.path}")
        if not force and (symlink or (previous is not None and previous != item.text and not is_generated(item.path, previous))):
            raise InstructionError(f"拒绝覆盖手写文件或软链接: {item.path}")
        if not symlink and previous == item.text:
            return False
        state = state_path(item.path)
        if not force and (state.is_symlink() or (
            state.exists() and (not state.is_file() or not read(state).startswith(MARKER + "\n"))
        )):
            raise InstructionError(f"拒绝覆盖已有记录文件: {state}")
        with tempfile.NamedTemporaryFile(mode="wb", dir=item.path.parent, prefix=f".{item.path.name}.", delete=False) as handle:
            temporary = Path(handle.name)
            handle.write(item.text.encode("utf-8"))
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary, item.path)
        temporary = None
        replaced = True
        with tempfile.NamedTemporaryFile(mode="wb", dir=item.path.parent, prefix=f".{item.path.name}.state.", delete=False) as handle:
            temporary = Path(handle.name)
            handle.write((MARKER + "\n" + item.text).encode("utf-8"))
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary, state_path(item.path))
        temporary = None
        return True
    except OSError as exc:
        detail = "；目标已替换，但记录可能未更新" if replaced else ""
        raise InstructionError(f"写入失败 {item.path}: {exc}{detail}") from exc
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)
        if fd is not None:
            os.close(fd)
            lock.unlink(missing_ok=True)


def execute(targets: list[str], all_targets: bool, dry_run: bool, force: bool, checking: bool, root: Path, test: bool) -> None:
    if all_targets and targets:
        raise typer.BadParameter("--all 不能与指定 target 一起使用")
    written = []
    try:
        plans = plan(root.resolve(), targets, force, not checking, test)
        mismatch = False
        for item in plans:
            different = item.symlink or item.previous != item.text
            if checking:
                typer.echo(f"{item.name}: {item.path} {'不一致' if different else '一致'}")
                mismatch |= different
            elif dry_run:
                typer.echo(f"{item.name}: {item.path}" + ("（将替换软链接本身）" if item.symlink else ""))
                if different:
                    diff = difflib.unified_diff((item.previous or "").splitlines(keepends=True), item.text.splitlines(keepends=True), fromfile="当前", tofile="生成")
                    sys.stdout.writelines(diff)
                else:
                    typer.echo("无变化")
            else:
                if test:
                    try:
                        item.path.parent.mkdir(parents=True, exist_ok=True)
                    except OSError as exc:
                        raise InstructionError(f"创建测试目标目录失败 {item.path.parent}: {exc}") from exc
                changed = write(item, force)
                if changed:
                    written.append(item.name)
                typer.echo(f"{item.name}: {item.path} {'已更新' if changed else '无变化'}")
        if mismatch:
            raise typer.Exit(1)
    except InstructionError as exc:
        typer.echo(f"错误: {exc}", err=True)
        if written:
            typer.echo(f"已更新: {', '.join(written)}；后续目标未处理。", err=True)
        raise typer.Exit(2) from exc


@app.command()
def sync(
    targets: Annotated[list[str] | None, typer.Argument(help="目标名称；省略时处理全部。")] = None,
    all_targets: Annotated[bool, typer.Option("--all", help="处理全部目标。")] = False,
    dry_run: Annotated[bool, typer.Option(help="只显示目标和差异。")] = False,
    force: Annotated[bool, typer.Option(help="允许替换手写文件或软链接本身。")] = False,
    root: Annotated[Path, typer.Option(help="项目根目录，默认为当前目录。")] = Path("."),
    test: Annotated[bool, typer.Option("--test", help="使用各 target 的测试输出路径。")] = False,
) -> None:
    execute(targets or [], all_targets, dry_run, force, False, root, test)


@app.command()
def check(
    targets: Annotated[list[str] | None, typer.Argument(help="目标名称；省略时检查全部。")] = None,
    all_targets: Annotated[bool, typer.Option("--all", help="检查全部目标。")] = False,
    root: Annotated[Path, typer.Option(help="项目根目录，默认为当前目录。")] = Path("."),
    test: Annotated[bool, typer.Option("--test", help="使用各 target 的测试输出路径。")] = False,
) -> None:
    execute(targets or [], all_targets, False, False, True, root, test)
